/**
 * Extension function to translate any string. Uses the device's active locale.
 * Falls back to English (the string itself) if no translation is found.
 */
@Composable
fun String.tr(): String {
    val currentLang by LocaleManager.currentLanguage.collectAsState()
    return when (currentLang) {
        "hi" -> hindiTranslations[this] ?: this
        "bn" -> bengaliTranslations[this] ?: this
        else -> this
    }
}

/**
 * Non-composable version for use outside of Composable context (lambdas, callbacks, etc).
 */
fun String.trNonComposable(): String {
    val currentLang = LocaleManager.currentLanguage.value
    return when (currentLang) {
        "hi" -> hindiTranslations[this] ?: this
        "bn" -> bengaliTranslations[this] ?: this
        else -> this
    }
}
